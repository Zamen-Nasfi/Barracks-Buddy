const LOCALE_KEY = "bms.locale";

function RootShell({ children }: { children: ReactNode }) {
  return (
    <html lang="ar" dir="rtl">
      <head>
        <HeadContent />
      </head>
      <body>
        {children}
        <Scripts />
      </body>
    </html>
  );
}

function RootComponent() {
  const { queryClient } = Route.useRouteContext();
  const router = useRouter();
  const [locale, setLocaleState] = useState<Locale>("ar");

  useEffect(() => {
    const saved = window.localStorage.getItem(LOCALE_KEY) as Locale | null;
    if (saved && LOCALES.some((l) => l.code === saved)) setLocaleState(saved);
  }, []);

  useEffect(() => {
    const def = LOCALES.find((l) => l.code === locale)!;
    document.documentElement.lang = locale;
    document.documentElement.dir = def.dir;
  }, [locale]);

  const setLocale = (l: Locale) => {
    window.localStorage.setItem(LOCALE_KEY, l);
    setLocaleState(l);
  };

  useEffect(() => {
    const { data } = supabase.auth.onAuthStateChange((event) => {
      if (event !== "SIGNED_IN" && event !== "SIGNED_OUT" && event !== "USER_UPDATED") return;
      router.invalidate();
      if (event !== "SIGNED_OUT") queryClient.invalidateQueries();
    });
    return () => data.subscription.unsubscribe();
  }, [router, queryClient]);

  return (
    <QueryClientProvider client={queryClient}>
      <LocaleContext.Provider value={{ locale, setLocale }}>
        {/* Required: nested routes render here. Removing <Outlet /> breaks all child routes. */}
        <Outlet />
        <Toaster position={locale === "ar" ? "bottom-left" : "bottom-right"} richColors />
      </LocaleContext.Provider>
    </QueryClientProvider>
  );
}